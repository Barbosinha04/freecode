import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
import numpy as np

# 1. Importar os dados
df = pd.read_csv('https://raw.githubusercontent.com/freeCodeCamp/boilerplate-medical-data-visualizer/main/medical_examination.csv')

# 2. Adicionar a coluna 'overweight' (IMC)
# Altura dividida por 100 para converter cm em metros
df['overweight'] = (df['weight'] / ((df['height'] / 100) ** 2) > 25).astype(int)

# 3. Normalizar dados (0 é bom, 1 é ruim)
# Se colesterol ou glicose for 1 (normal), vira 0. Se for > 1, vira 1.
df['cholesterol'] = (df['cholesterol'] > 1).astype(int)
df['gluc'] = (df['gluc'] > 1).astype(int)

# Função para desenhar o Gráfico Categórico
def draw_cat_plot():
    # 5. Criar DataFrame para o cat plot usando pd.melt
    # Mantemos 'cardio' fixo e derretemos o resto
    df_cat = pd.melt(df, id_vars=['cardio'], value_vars=['cholesterol', 'gluc', 'smoke', 'alco', 'active', 'overweight'])

    # 6. Agrupar e reformatar os dados
    # Contamos quantos valores 0 e 1 existem para cada categoria, divididos por cardio
    df_cat = df_cat.groupby(['cardio', 'variable', 'value']).size().reset_index(name='total')

    # 7. Criar o gráfico
    # kind='bar' cria as barras
    fig = sns.catplot(x='variable', y='total', hue='value', col='cardio', data=df_cat, kind='bar').fig

    # 8. Get the figure for the output (Isso já foi feito na linha acima com .fig)

    # 9. Salvar a imagem (Não modifique)
    fig.savefig('catplot.png')
    return fig


# Função para desenhar o Mapa de Calor
def draw_heat_map():
    # 11. Limpar os dados (Filtros de dados incorretos)
    df_heat = df[
        (df['ap_lo'] <= df['ap_hi']) & # Pressão diastólica não pode ser maior que sistólica
        (df['height'] >= df['height'].quantile(0.025)) & # Remover 2.5% mais baixos
        (df['height'] <= df['height'].quantile(0.975)) & # Remover 2.5% mais altos
        (df['weight'] >= df['weight'].quantile(0.025)) & # Remover 2.5% mais leves
        (df['weight'] <= df['weight'].quantile(0.975))   # Remover 2.5% mais pesados
    ]

    # 12. Calcular a matriz de correlação
    corr = df_heat.corr()

    # 13. Gerar a máscara para o triângulo superior
    mask = np.triu(np.ones_like(corr, dtype=bool))

    # 14. Configurar a figura do matplotlib
    fig, ax = plt.subplots(figsize=(11, 9))

    # 15. Plotar o mapa de calor
    # annot=True mostra os números, fmt='.1f' deixa com 1 casa decimal
    sns.heatmap(corr, mask=mask, annot=True, fmt='.1f', center=0, vmin=-0.1, vmax=0.25, square=True, linewidths=.5, cbar_kws={'shrink': .5})

    # 16. Salvar a imagem (Não modifique)
    fig.savefig('heatmap.png')
    return fig



