import pandas as pd

def calculate_demographic_data(print_data=True):
    # Lê os dados do arquivo CSV
    df = pd.read_csv('adult.data.csv')

    # ---------------------------------------------------------
    # 1. Quantas pessoas de cada raça estão representadas neste conjunto de dados?
    race_count = df['race'].value_counts()

    # ---------------------------------------------------------
    # 2. Qual é a idade média dos homens?
    average_age_men = round(df[df['sex'] == 'Male']['age'].mean(), 1)

    # ---------------------------------------------------------
    # 3. Qual é a porcentagem de pessoas que têm diploma de Bacharel (Bachelors)?
    percentage_bachelors = round(len(df[df['education'] == 'Bachelors']) / len(df) * 100, 1)

    # ---------------------------------------------------------
    # 4. Qual a porcentagem de pessoas com educação avançada que ganham >50K?
    # Educação avançada: `Bachelors`, `Masters`, ou `Doctorate`

    # Filtra quem tem educação avançada
    q4_higher = df['education'].isin(['Bachelors', 'Masters', 'Doctorate'])

    # Filtra quem NÃO tem educação avançada (usando o ~)
    q4_lower = ~df['education'].isin(['Bachelors', 'Masters', 'Doctorate'])

    # Conta o total de pessoas em cada grupo
    higher_education = df[q4_higher]
    lower_education = df[q4_lower]

    # Calcula a porcentagem de ricos no grupo COM diploma
    # (Ricos com diploma / Total com diploma) * 100
    if len(higher_education) > 0:
        higher_education_rich = round(len(higher_education[higher_education['salary'] == '>50K']) / len(higher_education) * 100, 1)
    else:
        higher_education_rich = 0.0

    # ---------------------------------------------------------
    # 5. Qual a porcentagem de pessoas SEM educação avançada que ganham >50K?
    # (Ricos sem diploma / Total sem diploma) * 100
    if len(lower_education) > 0:
        lower_education_rich = round(len(lower_education[lower_education['salary'] == '>50K']) / len(lower_education) * 100, 1)
    else:
        lower_education_rich = 0.0

    # ---------------------------------------------------------
    # 6. Qual é o número mínimo de horas que uma pessoa trabalha por semana?
    min_work_hours = df['hours-per-week'].min()

    # ---------------------------------------------------------
    # 7. Qual a porcentagem de pessoas que trabalham o mínimo de horas e ganham >50K?

    # Filtra quem trabalha o mínimo de horas
    num_min_workers = df[df['hours-per-week'] == min_work_hours]

    # Conta quantos desses são ricos
    rich_min_workers = len(num_min_workers[num_min_workers['salary'] == '>50K'])

    # Calcula a porcentagem
    if len(num_min_workers) > 0:
        rich_percentage = round((rich_min_workers / len(num_min_workers)) * 100, 1)
    else:
        rich_percentage = 0.0

    # ---------------------------------------------------------
    # 8. Qual país tem a maior porcentagem de pessoas que ganham >50K?

    # Conta total de pessoas por país
    country_count = df['native-country'].value_counts()

    # Conta total de ricos por país
    country_rich_count = df[df['salary'] == '>50K']['native-country'].value_counts()

    # Divide um pelo outro para achar a porcentagem de cada país
    highest_earning_country_percentage_list = (country_rich_count / country_count) * 100

    # Pega o nome do país com a maior porcentagem (.idxmax)
    highest_earning_country = highest_earning_country_percentage_list.idxmax()

    # Pega o valor da maior porcentagem (.max) e arredonda
    highest_earning_country_percentage = round(highest_earning_country_percentage_list.max(), 1)

    # ---------------------------------------------------------
    # 9. Identifique a ocupação mais popular para quem ganha >50K na Índia.
    pessoa_india = dataframe[(dataframe['native-country'] == 'India') & (dataframe['salary'] == '>50K')]
resposta = pessoa_india['occupation'].value_counts().idxmax()
